CrtcList

	;	this list is read in reverse order of byte pairs

	;	screen start address
	db	CRTC_REGISTER_SCREEN_START_H, (INTRO_SCREEN_START_ADDRESS >> 3) >> 8
	db	CRTC_REGISTER_SCREEN_START_L, (INTRO_SCREEN_START_ADDRESS >> 3) & $ff

	;	screen width
	db	CRTC_REGISTER_HORIZONTAL_DISPLAYED, INTRO_SCREEN_BYTE_COLUMNS

	;	screen left indent
	db	CRTC_REGISTER_HORIZONTAL_SYNC_POSITION, 98 - ((320 - INTRO_SCREEN_PIXEL_WIDTH) / 8)

	;	screen character rows
	db	CRTC_REGISTER_VERTICAL_DISPLAYED, INTRO_SCREEN_DISPLAYED_ROWS

	;	screen and cursor off
	db	CRTC_REGISTER_INTERLACE_DELAY_DISABLE, CRTC_INTERLACE_DELAY_DISABLE_DISPLAY_OFF | CRTC_INTERLACE_DELAY_DISABLE_CURSOR_OFF

CrtcList_end
